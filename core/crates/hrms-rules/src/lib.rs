/// گرد کردن به دو رقم اعشار با رفتار نیم‌به‌بالا (هم‌رفتار با پیاده‌سازی سرور).
pub fn round2(x: f64) -> f64 {
    (x * 100.0 + 0.5 * x.signum()).trunc() / 100.0
}

/// گرد کردن به نزدیک‌ترین عدد صحیح با رفتار نیم‌به‌بالا (برای مبالغ ریالی).
pub fn round_half_up(x: f64) -> i64 {
    if x >= 0.0 {
        (x + 0.5).floor() as i64
    } else {
        -((-x + 0.5).floor() as i64)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rounding_matches_server_side_behaviour() {
        assert_eq!(round2(3.855), 3.86);
        assert_eq!(round2(3.854), 3.85);
        assert_eq!(round_half_up(4270000.5), 4270001);
        assert_eq!(round_half_up(-1.5), -2);
    }
}
